export const getCategoryDefaultImage = (categoryId: string, itemId?: string): string => {
  const arr = CATEGORY_IMAGE_ARRAYS[categoryId];
  if (!arr || arr.length === 0) {
    return 'https://images.unsplash.com/photo-1486406146926-c627a92ad1ab?w=800&auto=format&fit=crop&q=80';
  }
  if (!itemId) return arr[0];
  let hash = 0;
  for (let i = 0; i < itemId.length; i++) {
    hash = itemId.charCodeAt(i) + ((hash << 5) - hash);
  }
  const index = Math.abs(hash) % arr.length;
  return arr[index];
};
